<#
.SYNOPSIS
    Builds the dashbls dependency (relic + BLS wrapper) for the native MSVC build.

.DESCRIPTION
    The MSVC solution (build_msvc\syscoin.sln) links dashbls as prebuilt static
    libraries instead of compiling the sources in-tree. This script configures
    the bundled dashbls CMake project (src\dashbls) with the Visual Studio 2022
    generator and builds the relic static library first, then the dashbls static
    wrapper against it.

    Outputs (for -Configuration Release; Debug uses the same layout with a
    "Debug" folder instead of "Release"):
        src\dashbls\build\src\<Config>\dashbls.lib
        src\dashbls\build\depends\relic\lib\<Config>\relic_s.lib
        src\dashbls\build\depends\mimalloc\<Config>\mimalloc-static.lib

    The relic config header is generated by relic's CMake configure step at:
        src\dashbls\build\depends\relic\include\relic_conf.h

    common.init.vcxproj(.in) must add that directory (plus
    src\dashbls\include, src\dashbls\depends\relic\include and
    src\dashbls\depends\mimalloc\include) to AdditionalIncludeDirectories and
    the three .lib files above to the link inputs.

.EXAMPLE
    .\build_msvc\build-dashbls.ps1
    .\build_msvc\build-dashbls.ps1 -Configuration Debug -Clean
#>

[CmdletBinding()]
param(
    [Parameter()]
    [ValidateSet("Debug", "Release")]
    [string]$Configuration = "Release",

    [Parameter()]
    [ValidateSet("x64")]
    [string]$Platform = "x64",

    [Parameter()]
    [string]$BuildDir = "",

    [Parameter()]
    [switch]$Clean
)

$ErrorActionPreference = "Stop"

function Invoke-Checked {
    param(
        [Parameter(Mandatory = $true)]
        [string]$StepName,
        [Parameter(Mandatory = $true)]
        [scriptblock]$Command
    )
    Write-Host ""
    Write-Host "=== $StepName ==="
    # Dot-source (not &) so $LASTEXITCODE below is read in this exact scope.
    . $Command
    if ($LASTEXITCODE -ne 0) {
        throw "$StepName failed with exit code $LASTEXITCODE"
    }
}

# --- Locate the repository and the dashbls sources ---------------------------
$RepoRoot = (Get-Item (Join-Path $PSScriptRoot "..")).FullName
$DashblsDir = Join-Path $RepoRoot "src\dashbls"
if (-not (Test-Path (Join-Path $DashblsDir "CMakeLists.txt"))) {
    throw "dashbls CMake project not found at $DashblsDir"
}
if ([string]::IsNullOrEmpty($BuildDir)) {
    $BuildDir = Join-Path $DashblsDir "build"
}
Write-Host "Repository root : $RepoRoot"
Write-Host "dashbls sources : $DashblsDir"
Write-Host "Build directory : $BuildDir"
Write-Host "Configuration   : $Configuration ($Platform)"

# --- Prerequisite: cmake ------------------------------------------------------
$cmake = Get-Command "cmake" -ErrorAction SilentlyContinue
if ($null -eq $cmake) {
    throw "cmake was not found in PATH. Install CMake 3.14+ (https://cmake.org/download/) and re-run."
}
Write-Host "cmake           : $($cmake.Source)"

# --- (Re)create the out-of-source build directory -----------------------------
if ($Clean -and (Test-Path $BuildDir)) {
    Write-Host "Removing previous build directory ($BuildDir)..."
    Remove-Item -Recurse -Force $BuildDir
}
New-Item -ItemType Directory -Force -Path $BuildDir | Out-Null

# --- Configure + build ---------------------------------------------------------
Push-Location $BuildDir
try {
    # Configure relic + mimalloc + dashbls for MSVC x64.
    #
    # Notes on the flags:
    #  - "Visual Studio 17 2022" / -A x64 is the 64-bit VS 2022 toolchain required
    #    by build_msvc (see build_msvc\README.md).
    #  - The dashbls top-level CMakeLists.txt already pins every relic option
    #    (ARITH easy/gmp, WSIZE 64, TIMER ANSI, MULTI OPENMP, SEED WCGR,
    #    FP_QNRES on, ...); this step generates depends\relic\include\relic_conf.h
    #    into the build tree, which the .vcxproj include path must reference.
    #  - CMAKE_MSVC_RUNTIME_LIBRARY=MultiThreaded[$<CONFIG:Debug>:Debug] selects
    #    the static CRT (/MT, /MTd) to match common.init.vcxproj (syscoin links
    #    everything statically); -DRUNTIME=MT tells relic's own flag handling
    #    the same thing. Mixing /MT syscoin objects with /MD dashbls libs would
    #    fail the link with LNK2038/LNK2005.
    #  - Bindings, tests and benchmarks are disabled: the MSVC build only needs
    #    the static libraries (and building them needs no Python/pybind11).
    Invoke-Checked "Configuring dashbls for MSVC $Platform [$Configuration]" {
        & cmake -G "Visual Studio 17 2022" -A x64 `
            -DCMAKE_BUILD_TYPE="$Configuration" `
            '-DCMAKE_MSVC_RUNTIME_LIBRARY=MultiThreaded$<$<CONFIG:Debug>:Debug>' `
            -DRUNTIME=MT `
            -DBUILD_BLS_PYTHON_BINDINGS=0 `
            -DBUILD_BLS_TESTS=0 `
            -DBUILD_BLS_BENCHMARKS=0 `
            $DashblsDir
    }

    # Phase 1: relic static library (target name "relic_s").
    Invoke-Checked "Building relic (static) [$Configuration]" {
        & cmake --build . --config $Configuration --target relic_s --parallel
    }

    # Phase 2: the dashbls BLS wrapper, linked against the relic built above.
    # (Its mimalloc-static dependency is built automatically as needed.)
    Invoke-Checked "Building dashbls (static) [$Configuration]" {
        & cmake --build . --config $Configuration --target dashbls --parallel
    }
}
finally {
    Pop-Location
}

# --- Verify the expected outputs ----------------------------------------------
$ExpectedOutputs = @(
    (Join-Path $BuildDir "src\$Configuration\dashbls.lib"),
    (Join-Path $BuildDir "depends\relic\lib\$Configuration\relic_s.lib"),
    (Join-Path $BuildDir "depends\mimalloc\$Configuration\mimalloc-static.lib"),
    (Join-Path $BuildDir "depends\relic\include\relic_conf.h")
)
$Missing = @()
foreach ($Output in $ExpectedOutputs) {
    if (Test-Path $Output) {
        Write-Host "  OK: $Output"
    } else {
        $Missing += $Output
    }
}
if ($Missing.Count -gt 0) {
    throw "Build finished but the following expected outputs are missing:`n$($Missing -join "`n")"
}

Write-Host ""
Write-Host "dashbls MSVC $Platform $Configuration build complete."
Write-Host "Next: run 'python build_msvc\msvc-autogen.py' and build build_msvc\syscoin.sln with msbuild."
